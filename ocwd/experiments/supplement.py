        parts.append("\\section{Operating points and calibration}\nThe threshold is set to reach the stated detection rate for the given wear stage; false alarms are counted on the real healthy windows of held-out vehicles.\n"
                     + table("False alarms at fixed detection rates.", "tab:s_op",
                             ["Corpus", "Stage", "Detection", "FPR healthy", "False alarms / h", "FPR confounders"], rows[:-1])
                     + table("Calibration of the ECTA wear probability (wear vs.\\ all).", "tab:s_cal", ["Corpus", "Brier", "ECE"], cal))
