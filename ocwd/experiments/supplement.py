def j(name):
    p = R / name
    return json.load(open(p, encoding="utf-8")) if p.exists() else None


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def _esc(c):
    c = str(c)
    if "$" in c or "\\" in c:
        return c
    return c.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def table(caption, label, cols, rows, align=None, size="\\footnotesize"):
    align = align or "l" + "c" * (len(cols) - 1)
    s = [f"\\begin{{table}}[!htbp]\n\\centering\n\\caption{{{caption}}}\\label{{{label}}}\n{size}\n"
         f"\\resizebox{{\\linewidth}}{{!}}{{%\n\\begin{{tabular}}{{@{{}}{align}@{{}}}}\n\\toprule\n"
         + " & ".join(cols) + " \\\\\n\\midrule\n"]
    for r in rows:
        s.append("\\midrule\n" if r == "MID" else " & ".join(_esc(c) for c in r) + " \\\\\n")
    s.append("\\bottomrule\n\\end{tabular}}\n\\end{table}\n")
    return "".join(s)


